function coordinationStudentDrill(name, opts) {
  return {
    name: name,
    focus: !!(opts && opts.focus),
    dose: opts.dose,
    rest: opts.rest
  };
}

function coordinationCoachDrill(name, opts) {
  var base = window.COORDINATION_DRILL_BANK[name];
  return {
    name: name,
    focus: !!(opts && opts.focus),
    core: base.core,
    steps: base.steps,
    errors: base.errors,
    dose: opts.coachDose || opts.dose,
    safety: base.safety
  };
}

function coordinationLessonDrills(items) {
  return {
    student: items.map(function (it) {
      return coordinationStudentDrill(it.name, it);
    }),
    coach: items.map(function (it) {
      return coordinationCoachDrill(it.name, it);
    })
  };
}

